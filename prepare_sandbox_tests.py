
import ast
import json
import shutil
from pathlib import Path

from patch_validator import validate_patch

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "verification_bundle"


def prepare_sandbox_tests():
    # Validate the Nemotron proposal before preparing it.
    valid, reason = validate_patch()

    if not valid:
        raise ValueError(f"Patch rejected: {reason}")

    # Read the original code and AI-generated function.
    original = (ROOT / "transactions.py").read_text(
        encoding="utf-8"
    )

    patch = json.loads(
        (ROOT / "proposed_patch.json").read_text(
            encoding="utf-8"
        )
    )

    proposed_function = patch["proposed_code"]

    # Locate the original calculate_total() function.
    tree = ast.parse(original)

    function = next(
        node for node in tree.body
        if isinstance(node, ast.FunctionDef)
        and node.name == "calculate_total"
    )

    # Replace ONLY the original function's source lines.
    # Everything else, including transaction data, stays.
    lines = original.splitlines(keepends=True)

    repaired = (
        "".join(lines[:function.lineno - 1])
        + proposed_function.rstrip()
        + "\n"
        + "".join(lines[function.end_lineno:])
    )

    # Confirm that all top-level code outside the repaired
    # function is structurally unchanged.
    repaired_tree = ast.parse(repaired)

    def unchanged_nodes(parsed_tree):
        return [
            ast.dump(node, include_attributes=False)
            for node in parsed_tree.body
            if not (
                isinstance(node, ast.FunctionDef)
                and node.name == "calculate_total"
            )
        ]

    if unchanged_nodes(tree) != unchanged_nodes(repaired_tree):
        raise ValueError("Patch changed code outside calculate_total.")

    # Save a disposable test package.
    OUTPUT.mkdir(exist_ok=True)

    (OUTPUT / "transactions.py").write_text(
        repaired, encoding="utf-8"
    )

    shutil.copyfile(
        ROOT / "test_transactions.py",
        OUTPUT / "test_transactions.py"
    )

    # Independent financial tests, not generated by Nemotron.
    regression_tests = '''
import copy
import unittest
from transactions import calculate_total, transactions


class FinancialRegressionTests(unittest.TestCase):

    def test_original_transactions_preserved(self):
        self.assertEqual(len(transactions), 5)
        self.assertEqual(
            [t["id"] for t in transactions],
            ["TXN001", "TXN002", "TXN003",
             "TXN004", "TXN002"]
        )

    def test_original_total(self):
        self.assertEqual(calculate_total(transactions), 400)

    def test_duplicate_payment(self):
        data = [
            {"id": "A", "type": "Payment", "amount": 100},
            {"id": "A", "type": "Payment", "amount": 100},
            {"id": "B", "type": "Refund", "amount": 30}
        ]
        self.assertEqual(calculate_total(data), 70)

    def test_duplicate_refund(self):
        data = [
            {"id": "A", "type": "Payment", "amount": 100},
            {"id": "B", "type": "Refund", "amount": 40},
            {"id": "B", "type": "Refund", "amount": 40}
        ]
        self.assertEqual(calculate_total(data), 60)

    def test_empty_transactions(self):
        self.assertEqual(calculate_total([]), 0)

    def test_input_not_modified(self):
        before = copy.deepcopy(transactions)
        calculate_total(transactions)
        self.assertEqual(transactions, before)
'''

    (OUTPUT / "test_financial_regression.py").write_text(
        regression_tests, encoding="utf-8"
    )

    print("ROOTCAUSE AI - SANDBOX TEST PREPARATION")
    print("=" * 45)
    print("AI-generated function inserted into a copy.")
    print("Original transactions.py remains unchanged.")
    print("Existing pytest test copied.")
    print("Independent financial regression tests created.")
    print("Package: verification_bundle")
    print("Status: READY FOR SANDBOX - NOT VERIFIED")


if __name__ == "__main__":
    prepare_sandbox_tests()
